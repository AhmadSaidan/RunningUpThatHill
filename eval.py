"""The referee. Scores out/ by bits per byte (bpb) on the validation text: lower is better.
Do not edit this file.

Usage: python eval.py [max_bytes]
"""
import math
import os
import sys

import numpy as np
import torch
import torch.nn.functional as F

from model import load_model
from tokenizer import load_tokenizer

out_dir = "out"
max_bytes = int(sys.argv[1]) if len(sys.argv) > 1 else None
device = "cuda" if torch.cuda.is_available() else "mps" if torch.backends.mps.is_available() else "cpu"

# 1. Size: model.py, tokenizer.py and everything in out/ count towards the limit.
files = ["model.py", "tokenizer.py"] + [os.path.join(d, f) for d, _, fs in os.walk(out_dir) for f in fs]
size = sum(os.path.getsize(f) for f in files)
print(f"size: {size:,} bytes")
assert max_bytes is None or size <= max_bytes, f"too big: {size:,} > {max_bytes:,} bytes"

# 2. The tokenizer must be lossless.
tok = load_tokenizer(out_dir)
with open("data/val.txt", "rb") as f:
    text = f.read()
ids = tok.encode(text)
assert tok.decode(ids) == text, "tokenizer is not lossless"
print(f"bytes per token: {len(text) / len(ids):.4f}")

# 3. The model must not see future tokens, or other rows of the batch.
model = load_model(out_dir).to(device).eval()
T = model.block_size
with torch.no_grad():
    x = torch.randint(0, tok.vocab_size, (4, T), device=device)
    x2 = x.clone()
    x2[0, T // 2 :] = torch.randint(0, tok.vocab_size, (T - T // 2,), device=device)
    x2[1:] = torch.randint(0, tok.vocab_size, (3, T), device=device)
    a = F.log_softmax(model(x)[0, : T // 2].float(), dim=-1)
    b = F.log_softmax(model(x2)[0, : T // 2].float(), dim=-1)
    assert torch.allclose(a, b, atol=1e-3), "model can see the future or other batch rows"

# 4. bpb = total negative log-likelihood (in bits) of every val token / number of val bytes.
#    The text is cut into non-overlapping windows of T tokens; a BOS token starts the first one.
ids = torch.from_numpy(np.concatenate([[tok.bos], ids]).astype(np.int64))


def nll(x, y):
    """Sum of -log p(y | x) in nats. cross_entropy applies log_softmax, so any logits are fair."""
    logits = model(x.to(device)).float()
    return F.cross_entropy(logits.flatten(0, 1), y.to(device).flatten(), reduction="sum").item()


n = (len(ids) - 1) // T  # number of full windows
total = 0.0
with torch.no_grad():
    for i in range(0, n, 32):
        j = min(i + 32, n)
        total += nll(ids[i * T : j * T].view(-1, T), ids[i * T + 1 : j * T + 1].view(-1, T))
    if len(ids) - 1 > n * T:  # the leftover partial window
        total += nll(ids[n * T : -1][None], ids[n * T + 1 :][None])

print(f"val bpb: {total / math.log(2) / len(text):.4f}")
